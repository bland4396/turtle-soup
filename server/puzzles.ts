export function getPuzzleById(id: string): Puzzle | undefined {
  return BUILTIN_PUZZLES.find((p) => p.id === id);
}

export function getRandomPuzzle(excludeId?: string): Puzzle {
  const pool = excludeId ? BUILTIN_PUZZLES.filter((p) => p.id !== excludeId) : BUILTIN_PUZZLES;
  const list = pool.length > 0 ? pool : BUILTIN_PUZZLES;
  return list[Math.floor(Math.random() * list.length)];
}
